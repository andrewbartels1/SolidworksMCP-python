"""Regenerate ``src/solidworks_mcp/adapters/sw_feature_errors.py`` from swconst.tlb.

The ``swFeatureError_e`` values returned by ``IFeature::GetErrorCode2`` and
``IModelDocExtension::GetWhatsWrong`` are read straight from the installed
SolidWorks constants type library, so they are never hand-typed (hand-typed
enum values have been wrong before - see #60).

Usage (Windows, SolidWorks installed)::

    .\\.venv\\Scripts\\python.exe scripts\\gen_sw_feature_errors.py
    .\\.venv\\Scripts\\python.exe scripts\\gen_sw_feature_errors.py --tlb "<path>\\swconst.tlb"

Without ``--tlb`` the script looks in the usual SolidWorks install folders.
"""

from __future__ import annotations

import argparse
import glob
import sys
from pathlib import Path

ENUM_NAME = "swFeatureError_e"
OUTPUT = (
    Path(__file__).resolve().parents[1]
    / "src"
    / "solidworks_mcp"
    / "adapters"
    / "sw_feature_errors.py"
)
SEARCH_GLOBS = [
    r"C:\Program Files\Dassault Systemes\*\SOLIDWORKS\swconst.tlb",
    r"C:\Program Files\SOLIDWORKS Corp*\SOLIDWORKS\swconst.tlb",
]


def find_tlb() -> Path:
    """Return the first swconst.tlb found in the standard install folders."""
    for pattern in SEARCH_GLOBS:
        hits = sorted(glob.glob(pattern))
        if hits:
            return Path(hits[-1])
    raise SystemExit("swconst.tlb not found; pass --tlb <path>")


def read_enum(tlb_path: Path, enum_name: str) -> dict[int, str]:
    """Read ``enum_name``'s ``value -> member name`` map from a type library."""
    import pythoncom

    tlb = pythoncom.LoadTypeLib(str(tlb_path))
    for i in range(tlb.GetTypeInfoCount()):
        if tlb.GetDocumentation(i)[0] != enum_name:
            continue
        info = tlb.GetTypeInfo(i)
        members: dict[int, str] = {}
        for j in range(info.GetTypeAttr().cVars):
            var = info.GetVarDesc(j)
            members.setdefault(int(var.value), info.GetNames(var.memid)[0])
        return dict(sorted(members.items()))
    raise SystemExit(f"{enum_name} not found in {tlb_path}")


def render(members: dict[int, str], tlb_path: Path) -> str:
    """Render the generated module source."""
    lines = [
        '"""SolidWorks ``swFeatureError_e`` codes (GENERATED - do not edit).',
        "",
        f"Generated by ``scripts/gen_sw_feature_errors.py`` from ``{tlb_path.name}``",
        f"({tlb_path.parent.parent.name}). Regenerate after a SolidWorks upgrade.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "SW_FEATURE_ERRORS: dict[int, str] = {",
    ]
    lines += [f'    {code}: "{name}",' for code, name in members.items()]
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Generate the module and report how many members were written."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tlb", type=Path, help="path to swconst.tlb")
    args = parser.parse_args(argv)
    tlb_path = args.tlb or find_tlb()
    members = read_enum(tlb_path, ENUM_NAME)
    OUTPUT.write_text(render(members, tlb_path), encoding="utf-8")
    print(f"wrote {len(members)} {ENUM_NAME} members to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
